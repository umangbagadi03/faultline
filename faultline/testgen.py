"""
Generate a pytest regression test from an autopsy.

The test file is self-contained (the failing trace is embedded) and has two tests:
  1. Faultline must keep detecting this failure in the recorded trace.
  2. Your agent, re-run on the same task, must NOT show this failure again.
     (Plug your agent in via `run_agent`; until then the test is skipped.)
"""

import re

from .schema import Hypothesis, Trace

TEMPLATE = '''"""
Regression test generated by Faultline.
Root cause: {failure_class} at step {step}: {title}
"""
import pytest

from faultline.detectors import run_detectors
from faultline.schema import Trace

RECORDED_TRACE = Trace.model_validate_json(r"""{trace_json}""")

TASK = {task!r}
FAILURE_CLASS = "{failure_class}"


def serious_classes(trace):
    return [s.failure_class for s in run_detectors(trace) if s.severity >= 2]


def test_recorded_failure_is_detected():
    assert FAILURE_CLASS in serious_classes(RECORDED_TRACE)


# Replace with a function that runs YOUR agent and returns a faultline Trace.
run_agent = None


@pytest.mark.skipif(run_agent is None, reason="plug in run_agent to test the live agent")
def test_agent_does_not_regress():
    trace = run_agent(TASK)
    assert FAILURE_CLASS not in serious_classes(trace)
'''


def safe_name(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def generate_test(trace: Trace, root: Hypothesis) -> str:
    clean = trace.model_copy(update={"label": None})
    return TEMPLATE.format(
        failure_class=root.failure_class,
        step=root.root_cause_step,
        title=root.title,
        trace_json=clean.model_dump_json(),
        task=trace.task,
    )


def regression_filename(trace: Trace) -> str:
    return f"test_regression_{safe_name(trace.id)}.py"
